#!/usr/bin/env python3
"""Generates the launcher icons (one vector foreground + mipmap XML + manifest alias per logo colour).
Source of truth: LogoStyle.presets in app/src/main/java/com/terminalf/app/core/Palettes.kt.
Run: python3 tools/gen_launcher_icons.py"""
import os
import re

import logo_common as L

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main")
RES = os.path.join(ROOT, "res")
DEFAULT_KEY = "silver"      # LauncherIcons.DEFAULT_KEY
ADAPTIVE_SCALE = 0.92

pal = open(os.path.join(ROOT, "java/com/terminalf/app/core/Palettes.kt"), encoding="utf-8").read()
styles = L.presets(pal)


def fg_xml(stops):
    paths = []
    for i, (d, (x1, y1, x2, y2)) in enumerate(zip(L.BARS, L.AXES)):
        paths.append(f"""        <path android:pathData="{d}">
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}"
                    android:endX="{x2}" android:endY="{y2}">
                    <item android:offset="0" android:color="{stops[i * 2]}"/>
                    <item android:offset="1" android:color="{stops[i * 2 + 1]}"/>
                </gradient>
            </aapt:attr>
        </path>
""")
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_launcher_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="1024" android:viewportHeight="1024">
    <group android:scaleX="{ADAPTIVE_SCALE}" android:scaleY="{ADAPTIVE_SCALE}" android:pivotX="512" android:pivotY="512">
{''.join(paths)}    </group>
</vector>
"""


def w(path, text):
    full = os.path.join(RES, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w", encoding="utf-8").write(text)


# Clean up files from previous runs (colour sets change over time).
for sub in ("drawable", "mipmap-anydpi", "mipmap-anydpi-v26"):
    d = os.path.join(RES, sub)
    if os.path.isdir(d):
        for fn in os.listdir(d):
            if re.match(r"ic_launcher_(fg_)?\w+\.xml$", fn) and fn not in ("ic_launcher_round.xml",):
                os.remove(os.path.join(d, fn))

aliases = []
for key, cols in styles:
    w(f"drawable/ic_launcher_fg_{key}.xml", fg_xml(L.ramp(cols)))
    adaptive = lambda: f"""<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_fg_{key}"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
"""
    if key == DEFAULT_KEY:
        icon = "@mipmap/ic_launcher"   # default icon: ready-made PNGs + adaptive vector
        for name in ("ic_launcher", "ic_launcher_round"):
            w(f"mipmap-anydpi-v26/{name}.xml", adaptive())
    else:
        icon = f"@mipmap/ic_launcher_{key}"
        w(f"mipmap-anydpi-v26/ic_launcher_{key}.xml", adaptive())
        # Android 7.x (API 24-25) has no adaptive icons: dark tile + logo layer.
        w(f"mipmap-anydpi/ic_launcher_{key}.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/ic_launcher_background"/>
    <item android:drawable="@drawable/ic_launcher_fg_{key}"/>
</layer-list>
""")
    cls = "Launcher" + "".join(p[:1].upper() + p[1:] for p in key.split("_"))
    enabled = "true" if key == DEFAULT_KEY else "false"
    aliases.append(f"""        <activity-alias
            android:name=".{cls}"
            android:enabled="{enabled}"
            android:exported="true"
            android:icon="{icon}"
            android:label="TerminalF"
            android:targetActivity=".MainActivity">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>
""")

w("values/ic_launcher_background.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{L.TILE}</color>
</resources>
""")
# Notification (status bar) icon: the F as a single white shape.
w("drawable/ic_stat_notify.xml", """<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="1024" android:viewportHeight="1024">
""" + "".join(f'    <path android:fillColor="#FFFFFF" android:pathData="{d}"/>\n' for d in L.BARS) + "</vector>\n")

man_path = os.path.join(ROOT, "AndroidManifest.xml")
man = open(man_path, encoding="utf-8").read()
man = re.sub(r"\n?\s*<!-- ALIAS-(?:BASLA|START).*?<!-- ALIAS-(?:BITIS|END) -->\n?", "\n", man, flags=re.S)
block = ("        <!-- ALIAS-START: generated by tools/gen_launcher_icons.py; do not edit by hand -->\n"
         + "\n".join(aliases) + "        <!-- ALIAS-END -->\n")
man = man.replace("        <provider", block + "\n        <provider", 1)
open(man_path, "w", encoding="utf-8").write(man)
print("Icons:", len(styles), [k for k, _ in styles])
